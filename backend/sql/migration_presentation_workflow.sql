CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Tabela `pecas` - Garantir coluna status com default 'UNDER_VALIDATION'
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'pecas') THEN
    CREATE TABLE public.pecas (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      category TEXT NOT NULL,
      price NUMERIC(12, 2) DEFAULT 0,
      description TEXT DEFAULT '',
      image TEXT DEFAULT '',
      status TEXT DEFAULT 'UNDER_VALIDATION',
      passport_id TEXT UNIQUE,
      expert_name TEXT DEFAULT 'Aguardando Curadoria',
      expert_date TEXT DEFAULT 'Pendente',
      owner_id TEXT,
      provenance TEXT DEFAULT 'Não informado',
      conservation_state TEXT DEFAULT 'Não informado',
      conservation_score INTEGER,
      history JSONB DEFAULT '[]'::jsonb,
      share_token TEXT UNIQUE,
      share_status TEXT NOT NULL DEFAULT 'active',
      is_published BOOLEAN NOT NULL DEFAULT true,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  ELSE
    ALTER TABLE public.pecas ALTER COLUMN status SET DEFAULT 'UNDER_VALIDATION';
  END IF;
END $$;

-- 2. Tabela `categorias_rastreadas` (Stage 2: Person B Tracks Categories)
CREATE TABLE IF NOT EXISTS public.categorias_rastreadas (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT NOT NULL,
  categoria TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, categoria)
);

CREATE INDEX IF NOT EXISTS idx_categorias_rastreadas_user_id ON public.categorias_rastreadas (user_id);
CREATE INDEX IF NOT EXISTS idx_categorias_rastreadas_categoria ON public.categorias_rastreadas (categoria);

-- 3. Tabela `notificacoes` (Stage 4 & Stage 6: Notifications to Person B)
CREATE TABLE IF NOT EXISTS public.notificacoes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT NOT NULL,
  tipo TEXT NOT NULL,
  titulo TEXT NOT NULL,
  mensagem TEXT NOT NULL,
  peca_id BIGINT REFERENCES public.pecas(id) ON DELETE SET NULL,
  passport_id TEXT,
  lida BOOLEAN NOT NULL DEFAULT false,
  acao_url TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Atualiza a constraint de tipo para incluir 'peca_pendente', 'peca_aprovada' e 'peca_cadastrada'
ALTER TABLE public.notificacoes DROP CONSTRAINT IF EXISTS notificacoes_tipo_check;
ALTER TABLE public.notificacoes ADD CONSTRAINT notificacoes_tipo_check CHECK (
  tipo IN (
    'peca_pendente',
    'peca_aprovada',
    'peca_cadastrada',
    'primeiro_investimento',
    'peca_compatível',
    'laudo_concluido',
    'lembrete_conservacao',
    'alerta_generico'
  )
);

CREATE INDEX IF NOT EXISTS idx_notificacoes_user_id ON public.notificacoes (user_id);
CREATE INDEX IF NOT EXISTS idx_notificacoes_user_lida ON public.notificacoes (user_id, lida);
CREATE INDEX IF NOT EXISTS idx_notificacoes_tipo ON public.notificacoes (tipo);
CREATE INDEX IF NOT EXISTS idx_notificacoes_peca_id ON public.notificacoes (peca_id);

-- 4. Tabela `preferencias_notificacao`
CREATE TABLE IF NOT EXISTS public.preferencias_notificacao (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id TEXT UNIQUE NOT NULL,
  alertas_ativos BOOLEAN NOT NULL DEFAULT true,
  lembretes_ativos BOOLEAN NOT NULL DEFAULT false,
  notificar_pecas_compativeis BOOLEAN NOT NULL DEFAULT true,
  notificar_laudo_concluido BOOLEAN NOT NULL DEFAULT true,
  frequencia_lembrete TEXT NOT NULL DEFAULT 'semestral',
  canal_email BOOLEAN NOT NULL DEFAULT false,
  canal_push BOOLEAN NOT NULL DEFAULT true,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_preferencias_user_id ON public.preferencias_notificacao (user_id);

-- 5. Row Level Security (RLS)
ALTER TABLE public.pecas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categorias_rastreadas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notificacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.preferencias_notificacao ENABLE ROW LEVEL SECURITY;

-- Políticas para `pecas`
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pecas' AND policyname = 'Public read pecas') THEN
    CREATE POLICY "Public read pecas" ON public.pecas FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pecas' AND policyname = 'Authenticated insert pecas') THEN
    CREATE POLICY "Authenticated insert pecas" ON public.pecas FOR INSERT WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'pecas' AND policyname = 'Update pecas') THEN
    CREATE POLICY "Update pecas" ON public.pecas FOR UPDATE USING (true);
  END IF;
END $$;

