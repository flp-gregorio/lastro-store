CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Criação da tabela `pecas` (caso ainda não exista)
CREATE TABLE IF NOT EXISTS public.pecas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  price NUMERIC(12, 2) DEFAULT 0,
  description TEXT DEFAULT '',
  image TEXT DEFAULT '',
  status TEXT DEFAULT 'em revisão',
  passport_id TEXT UNIQUE,
  expert_name TEXT DEFAULT 'Não informado',
  expert_date TEXT DEFAULT 'Não informado',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. Evolução da tabela `pecas` para suportar o Passaporte Digital P0 (RF01-RF04, RF15, RNF08, RNF11)
ALTER TABLE public.pecas
  ADD COLUMN IF NOT EXISTS owner_id TEXT,
  ADD COLUMN IF NOT EXISTS provenance TEXT DEFAULT 'Não informado',
  ADD COLUMN IF NOT EXISTS conservation_state TEXT DEFAULT 'Não informado',
  ADD COLUMN IF NOT EXISTS conservation_score INTEGER CHECK (conservation_score IS NULL OR (conservation_score >= 1 AND conservation_score <= 5)),
  ADD COLUMN IF NOT EXISTS history JSONB DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS share_token TEXT UNIQUE,
  ADD COLUMN IF NOT EXISTS share_status TEXT NOT NULL DEFAULT 'active' CHECK (share_status IN ('active', 'revoked')),
  ADD COLUMN IF NOT EXISTS share_revoked_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS is_published BOOLEAN NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Preenche `passport_id` e `share_token` não enumeráveis (RNF11) para registros antigos que estejam sem valor
UPDATE public.pecas
SET passport_id = 'LST-' || upper(encode(gen_random_bytes(6), 'hex'))
WHERE passport_id IS NULL OR passport_id = '' OR passport_id = 'Pendente';

UPDATE public.pecas
SET share_token = encode(gen_random_bytes(12), 'hex')
WHERE share_token IS NULL OR share_token = '';

-- Normaliza campos essenciais antigos com 'Pendente' ou NULL para 'Não informado' (RF03 / Critério de Aceite 4)
UPDATE public.pecas
SET provenance = 'Não informado'
WHERE provenance IS NULL OR trim(provenance) = '';

UPDATE public.pecas
SET conservation_state = 'Não informado'
WHERE conservation_state IS NULL OR trim(conservation_state) = '';

UPDATE public.pecas
SET history = '[]'::jsonb
WHERE history IS NULL;

-- Índices para abertura rápida do passaporte por link ou QR Code (RNF11, RNF12)
CREATE INDEX IF NOT EXISTS idx_pecas_passport_id ON public.pecas (passport_id);
CREATE INDEX IF NOT EXISTS idx_pecas_share_token ON public.pecas (share_token);
CREATE INDEX IF NOT EXISTS idx_pecas_owner_id ON public.pecas (owner_id);

-- ============================================================================
-- 3. Tabela `eventos` · Catálogo Mínimo de Eventos (RF19 / Seção 5.2 / RNF09)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.eventos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  event_name TEXT NOT NULL CHECK (
    event_name IN (
      -- Consulta e uso
      'passaporte_consultado',
      'laudo_aberto',
      'primeira_visita',
      'sessao_iniciada',
      -- Registro
      'peca_cadastrada',
      'passaporte_publicado',
      'passaporte_atualizado',
      'peca_registrada',
      -- Investimento
      'peca_salva',
      'lista_criada',
      -- Alertas
      'alerta_configurado',
      'alerta_desativado',
      -- Compartilhamento
      'link_gerado',
      'titularidade_transferida',
      -- Transação e qualidade
      'proposta_enviada',
      'proposta_aceita',
      'pagamento_retido',
      'conferencia_aprovada',
      'conferencia_contestada',
      'curadoria_decidida'
    )
  ),
  peca_id BIGINT REFERENCES public.pecas(id) ON DELETE SET NULL,
  passport_id TEXT,
  user_id TEXT,
  anonymous_id TEXT,
  origin TEXT NOT NULL DEFAULT 'direto' CHECK (
    origin IN (
      'link_vendedor',
      'qr',
      'alerta',
      'indicacao',
      'conteudo',
      'anuncio',
      'link_compartilhado',
      'direto'
    )
  ),
  is_owner BOOLEAN NOT NULL DEFAULT false,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_eventos_event_name_created ON public.eventos (event_name, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_eventos_passport_id ON public.eventos (passport_id);
CREATE INDEX IF NOT EXISTS idx_eventos_anonymous_id ON public.eventos (anonymous_id);
CREATE INDEX IF NOT EXISTS idx_eventos_user_id ON public.eventos (user_id);

-- ============================================================================
-- 4. Tabela `atribuicoes_origem` · Atribuição da Primeira Visita (RF20)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.atribuicoes_origem (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  anonymous_id TEXT UNIQUE NOT NULL,
  first_origin TEXT NOT NULL CHECK (
    first_origin IN (
      'link_vendedor',
      'qr',
      'alerta',
      'indicacao',
      'conteudo',
      'anuncio',
      'link_compartilhado',
      'direto'
    )
  ),
  first_passport_id TEXT,
  first_visit_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  user_id TEXT,
  linked_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_atribuicoes_origem_anonymous_id ON public.atribuicoes_origem (anonymous_id);
CREATE INDEX IF NOT EXISTS idx_atribuicoes_origem_user_id ON public.atribuicoes_origem (user_id);

